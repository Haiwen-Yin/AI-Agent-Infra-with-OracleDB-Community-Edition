DECLARE
    v_table_count NUMBER;
    v_column_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_table_count
    FROM USER_TABLES
    WHERE TABLE_NAME = 'APPROVAL_REQUESTS';

    IF v_table_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE APPROVAL_REQUESTS (
                APPROVAL_ID VARCHAR2(64) PRIMARY KEY,
                ENTITY_TYPE VARCHAR2(32) NOT NULL,
                ENTITY_ID VARCHAR2(64) NOT NULL,
                REQUESTED_BY VARCHAR2(64) NOT NULL,
                APPROVAL_STATUS VARCHAR2(16) DEFAULT 'PENDING' NOT NULL,
                APPROVED_BY VARCHAR2(64),
                APPROVED_AT TIMESTAMP,
                REJECT_REASON VARCHAR2(500),
                CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT CK_APPROVAL_STATUS CHECK (APPROVAL_STATUS IN ('PENDING','APPROVED','REJECTED')),
                CONSTRAINT CK_APPROVAL_ENTITY CHECK (ENTITY_TYPE IN ('STEP','LOOP','TOOL'))
            )
        ]';
    END IF;

    SELECT COUNT(*) INTO v_column_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'IDX_APPROVAL_STATUS';
    IF v_column_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_APPROVAL_STATUS ON ' ||
            'APPROVAL_REQUESTS(APPROVAL_STATUS, CREATED_AT DESC)';
    END IF;

    SELECT COUNT(*) INTO v_column_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'IDX_APPROVAL_ENTITY';
    IF v_column_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_APPROVAL_ENTITY ON ' ||
            'APPROVAL_REQUESTS(ENTITY_TYPE, ENTITY_ID)';
    END IF;

    SELECT COUNT(*) INTO v_column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'APPROVAL_REQUESTS'
      AND COLUMN_NAME = 'SLA_DEADLINE';

    IF v_column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE APPROVAL_REQUESTS ADD (' ||
            'SLA_DEADLINE TIMESTAMP, SLA_ESCALATE_TO VARCHAR2(64))';
    END IF;
END;
