CREATE TABLE EXECUTION_JOBS (
    JOB_ID VARCHAR2(64) PRIMARY KEY, JOB_TYPE VARCHAR2(32) NOT NULL,
    STATUS VARCHAR2(24) NOT NULL, AGENT_ID VARCHAR2(64) NOT NULL,
    PAYLOAD_JSON JSON NOT NULL, RESULT_JSON JSON, ERROR_MESSAGE VARCHAR2(2000),
    IDEMPOTENCY_KEY VARCHAR2(128) NOT NULL UNIQUE,
    ATTEMPT_COUNT NUMBER(5) DEFAULT 0 NOT NULL, MAX_ATTEMPTS NUMBER(5) DEFAULT 3 NOT NULL,
    LEASE_TOKEN VARCHAR2(128), LEASE_OWNER VARCHAR2(128), LEASE_UNTIL TIMESTAMP,
    REQUIRES_APPROVAL CHAR(1) DEFAULT 'Y' NOT NULL, APPROVED_BY VARCHAR2(64), APPROVED_AT TIMESTAMP,
    CANCEL_REQUESTED CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, COMPLETED_AT TIMESTAMP,
    CONSTRAINT CK_EJ_STATUS CHECK (STATUS IN ('WAITING_APPROVAL','PENDING','RUNNING','RETRY','SUCCEEDED','FAILED','CANCELLED','REJECTED'))
);
CREATE INDEX IDX_EJ_CLAIM ON EXECUTION_JOBS(STATUS, CREATED_AT);
CREATE INDEX IDX_EJ_LEASE ON EXECUTION_JOBS(STATUS, LEASE_UNTIL);

CREATE TABLE EXECUTION_ATTEMPTS (
    ATTEMPT_ID VARCHAR2(64) PRIMARY KEY, JOB_ID VARCHAR2(64) NOT NULL,
    ATTEMPT_NUMBER NUMBER(5) NOT NULL, LEASE_TOKEN VARCHAR2(128) NOT NULL,
    WORKER_ID VARCHAR2(128) NOT NULL, STATUS VARCHAR2(24) NOT NULL,
    RESULT_JSON JSON, ERROR_MESSAGE VARCHAR2(2000),
    STARTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, COMPLETED_AT TIMESTAMP,
    CONSTRAINT FK_EA_JOB FOREIGN KEY (JOB_ID) REFERENCES EXECUTION_JOBS(JOB_ID) ON DELETE CASCADE,
    CONSTRAINT UK_EA_ATTEMPT UNIQUE (JOB_ID, ATTEMPT_NUMBER)
