-- Synchronize only system-managed templates. Service/profile capability gates
-- remain authoritative for Enterprise-only actions.
DECLARE
    FUNCTION same_clob(p_left CLOB, p_right CLOB) RETURN NUMBER IS
    BEGIN
        IF p_left IS NULL OR p_right IS NULL THEN
            IF p_left IS NULL AND p_right IS NULL THEN RETURN 1; END IF;
            RETURN 0;
        END IF;
        IF DBMS_LOB.COMPARE(p_left, p_right) = 0 THEN RETURN 1; END IF;
        RETURN 0;
    END;
    PROCEDURE sync_role(p_code VARCHAR2, p_name VARCHAR2, p_permissions CLOB, p_scopes CLOB) IS
        l_name CX_ROLE_TEMPLATES.DISPLAY_NAME%TYPE;
        l_permissions CX_ROLE_TEMPLATES.PERMISSIONS_JSON%TYPE;
        l_scopes CX_ROLE_TEMPLATES.DATA_SCOPES_JSON%TYPE;
        l_managed CX_ROLE_TEMPLATES.MANAGED%TYPE;
    BEGIN
        BEGIN
            SELECT DISPLAY_NAME, PERMISSIONS_JSON, DATA_SCOPES_JSON, MANAGED
              INTO l_name, l_permissions, l_scopes, l_managed
              FROM CX_ROLE_TEMPLATES WHERE ROLE_CODE = p_code FOR UPDATE;
        EXCEPTION WHEN NO_DATA_FOUND THEN
            INSERT INTO CX_ROLE_TEMPLATES
                (ROLE_CODE, DISPLAY_NAME, PERMISSIONS_JSON, DATA_SCOPES_JSON, VERSION, MANAGED)
            VALUES (p_code, p_name, p_permissions, p_scopes, 1, 'Y');
            RETURN;
        END;
        IF l_managed = 'Y' AND (l_name <> p_name OR same_clob(l_permissions, p_permissions) = 0
                                OR same_clob(l_scopes, p_scopes) = 0) THEN
            UPDATE CX_ROLE_TEMPLATES SET DISPLAY_NAME = p_name, PERMISSIONS_JSON = p_permissions,
                   DATA_SCOPES_JSON = p_scopes, VERSION = NVL(VERSION, 1) + 1, UPDATED_AT = SYSTIMESTAMP
             WHERE ROLE_CODE = p_code;
        END IF;
    END;
