DELETE FROM CX_ORGANIZATION_CLOSURE;

MERGE INTO CX_ORGANIZATION_CLOSURE dst
USING (
    SELECT ANCESTOR_ID, DESCENDANT_ID, MIN(DEPTH) DEPTH
      FROM (
        SELECT CONNECT_BY_ROOT ORGANIZATION_ID ANCESTOR_ID,
               ORGANIZATION_ID DESCENDANT_ID, LEVEL - 1 DEPTH
          FROM CX_ORGANIZATIONS
         START WITH ORGANIZATION_ID IS NOT NULL
        CONNECT BY NOCYCLE PRIOR ORGANIZATION_ID = PARENT_ID
      )
     GROUP BY ANCESTOR_ID, DESCENDANT_ID
) src
ON (dst.ANCESTOR_ID = src.ANCESTOR_ID AND dst.DESCENDANT_ID = src.DESCENDANT_ID)
WHEN MATCHED THEN UPDATE SET dst.DEPTH = src.DEPTH, dst.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (ANCESTOR_ID, DESCENDANT_ID, DEPTH)
VALUES (src.ANCESTOR_ID, src.DESCENDANT_ID, src.DEPTH);

MERGE INTO CX_REPORTING_RELATIONSHIPS dst
USING (
    SELECT 'V431-RPT-' || SUBSTR(MIN(m.MEMBERSHIP_ID), 1, 119) RELATIONSHIP_ID,
           m.PRINCIPAL_ID, MIN(m.MANAGER_PRINCIPAL_ID) MANAGER_PRINCIPAL_ID
      FROM CX_ORGANIZATION_MEMBERS m
      JOIN CX_PRINCIPALS p ON p.PRINCIPAL_ID = m.PRINCIPAL_ID
                          AND p.PRINCIPAL_TYPE = 'HUMAN' AND p.STATUS = 'ACTIVE'
      JOIN CX_PRINCIPALS mgr ON mgr.PRINCIPAL_ID = m.MANAGER_PRINCIPAL_ID
                            AND mgr.PRINCIPAL_TYPE = 'HUMAN' AND mgr.STATUS = 'ACTIVE'
     WHERE m.MANAGER_PRINCIPAL_ID IS NOT NULL AND m.MANAGER_PRINCIPAL_ID <> m.PRINCIPAL_ID
       AND m.STATUS = 'ACTIVE' AND (m.VALID_UNTIL IS NULL OR m.VALID_UNTIL > SYSTIMESTAMP)
     GROUP BY m.PRINCIPAL_ID
