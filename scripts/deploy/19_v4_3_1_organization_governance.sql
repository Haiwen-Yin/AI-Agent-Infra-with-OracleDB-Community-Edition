DECLARE l_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO l_count FROM (
        SELECT PRINCIPAL_ID FROM CX_ORGANIZATION_MEMBERS
         WHERE MEMBERSHIP_KIND = 'PRIMARY' AND STATUS = 'ACTIVE'
         GROUP BY PRINCIPAL_ID HAVING COUNT(*) > 1
    );
    IF l_count > 0 THEN
        RAISE_APPLICATION_ERROR(-20031, 'v4.3.1 organization migration refused: a Human has multiple active primary memberships');
    END IF;
    SELECT COUNT(*) INTO l_count FROM USER_INDEXES WHERE INDEX_NAME = 'IDX_CX_ORG_ACTIVE_PRIMARY';
    IF l_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX IDX_CX_ORG_ACTIVE_PRIMARY ON CX_ORGANIZATION_MEMBERS(CASE WHEN MEMBERSHIP_KIND = ''PRIMARY'' AND STATUS = ''ACTIVE'' THEN PRINCIPAL_ID END)';
    END IF;
END;
