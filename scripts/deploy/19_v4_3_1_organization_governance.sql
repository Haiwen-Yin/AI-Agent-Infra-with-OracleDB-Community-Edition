DECLARE l_cycles NUMBER;
BEGIN
    SELECT COUNT(*) INTO l_cycles
      FROM (
        SELECT CONNECT_BY_ISCYCLE IS_CYCLE
          FROM CX_ORGANIZATIONS
         START WITH ORGANIZATION_ID IS NOT NULL
        CONNECT BY NOCYCLE PRIOR ORGANIZATION_ID = PARENT_ID
      )
     WHERE IS_CYCLE = 1;
    IF l_cycles > 0 THEN
        RAISE_APPLICATION_ERROR(-20033, 'v4.3.1 organization migration refused: hierarchy contains a cycle');
    END IF;
END;
