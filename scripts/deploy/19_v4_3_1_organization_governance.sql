-- Replace the v4.3.0 broad uniqueness rule. NULL keys are not indexed, so
-- OPERATOR, VIEWER and SPONSOR rows remain many-to-one while an active Agent
-- can have only one PRIMARY_OWNER.
DECLARE l_count NUMBER; l_duplicates NUMBER;
BEGIN
    SELECT COUNT(*) INTO l_duplicates FROM (
        SELECT AGENT_ID FROM CX_AGENT_RELATIONSHIPS
         WHERE RELATIONSHIP_ROLE = 'PRIMARY_OWNER' AND STATUS = 'ACTIVE'
         GROUP BY AGENT_ID HAVING COUNT(*) > 1
    );
    IF l_duplicates > 0 THEN
        RAISE_APPLICATION_ERROR(-20032, 'v4.3.1 organization migration refused: an Agent has multiple active primary owners');
    END IF;
    SELECT COUNT(*) INTO l_count FROM USER_INDEXES WHERE INDEX_NAME = 'IDX_CX_AGENT_PRIMARY_OWNER';
    IF l_count > 0 THEN EXECUTE IMMEDIATE 'DROP INDEX IDX_CX_AGENT_PRIMARY_OWNER'; END IF;
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX IDX_CX_AGENT_PRIMARY_OWNER ON CX_AGENT_RELATIONSHIPS(CASE WHEN RELATIONSHIP_ROLE = ''PRIMARY_OWNER'' AND STATUS = ''ACTIVE'' THEN AGENT_ID END)';
END;
