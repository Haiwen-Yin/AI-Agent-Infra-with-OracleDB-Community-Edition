CREATE OR REPLACE PROCEDURE safe_idx(p_sql IN VARCHAR2) IS
BEGIN
    EXECUTE IMMEDIATE p_sql;
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            DBMS_OUTPUT.PUT_LINE('SAFE_IDX error: ' || p_sql || ' - ' || SQLERRM);
        END IF;
END;
