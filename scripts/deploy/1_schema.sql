-- ENTITIES: Unified table replacing MEMORIES + MEMORY_NODES
CREATE TABLE ENTITIES (
    ENTITY_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENTITY_TYPE    VARCHAR2(32) NOT NULL,
    NAME           VARCHAR2(500) NOT NULL,
    DESCRIPTION    VARCHAR2(4000),
    CONTENT        CLOB,
    CATEGORY       VARCHAR2(100),
    PRIORITY       NUMBER DEFAULT 2,
    STATUS         VARCHAR2(32) DEFAULT 'ACTIVE',
    TAGS           JSON,
    METADATA       JSON,
    OWNED_BY_AGENT VARCHAR2(64),
    VISIBILITY     VARCHAR2(32) DEFAULT 'SHARED',
    ACCESSIBLE_TO  JSON,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP,
    EXPIRES_AT     TIMESTAMP,
    CONSTRAINT CK_ENTITY_TYPE CHECK (ENTITY_TYPE IN ('MEMORY','KNOWLEDGE','TASK_OUTPUT','EXPERIENCE')),
    CONSTRAINT CK_VISIBILITY CHECK (VISIBILITY IN ('PRIVATE','SHARED','COLLABORATIVE')),
    CONSTRAINT CK_ENTITY_STATUS CHECK (STATUS IN ('ACTIVE','ARCHIVED','DEPRECATED','DELETED'))
);

COMMENT ON TABLE ENTITIES IS 'Unified entity store: memories, knowledge, task outputs, experiences';
COMMENT ON COLUMN ENTITIES.ENTITY_TYPE IS 'Discriminator: MEMORY, KNOWLEDGE, TASK_OUTPUT, EXPERIENCE';
COMMENT ON COLUMN ENTITIES.VISIBILITY IS 'PRIVATE=owner only, SHARED=all agents, COLLABORATIVE=listed agents';
COMMENT ON COLUMN ENTITIES.ACCESSIBLE_TO IS 'JSON array of agent_ids with access when VISIBILITY=COLLABORATIVE';

-- ENTITY_EDGES: Unified edge table replacing MEMORY_EDGES + MEMORY_RELATIONSHIPS + KNOWLEDGE_GRAPH
CREATE TABLE ENTITY_EDGES (
    EDGE_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOURCE_ID  NUMBER NOT NULL,
    TARGET_ID  NUMBER NOT NULL,
    EDGE_TYPE  VARCHAR2(64) NOT NULL,
    STRENGTH   NUMBER DEFAULT 1.0,
    CONFIDENCE NUMBER DEFAULT 0.8,
    PROPERTIES JSON,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_EDGE_SOURCE FOREIGN KEY (SOURCE_ID) REFERENCES ENTITIES(ENTITY_ID) ON DELETE CASCADE,
    CONSTRAINT FK_EDGE_TARGET FOREIGN KEY (TARGET_ID) REFERENCES ENTITIES(ENTITY_ID) ON DELETE CASCADE,
    CONSTRAINT CK_STRENGTH CHECK (STRENGTH BETWEEN 0 AND 2),
    CONSTRAINT CK_CONFIDENCE CHECK (CONFIDENCE BETWEEN 0 AND 1)
);

COMMENT ON TABLE ENTITY_EDGES IS 'Unified edges: replaces MEMORY_EDGES + MEMORY_RELATIONSHIPS + KNOWLEDGE_GRAPH';
COMMENT ON COLUMN ENTITY_EDGES.EDGE_TYPE IS 'Edge types: DEPENDS_ON, RELATED_TO, DERIVED_FROM, CAUSES, ENABLES, PREVENTS, SIMILAR_TO, EVOLVED_FROM, CONTRADICTS, SUPPORTS';

-- KNOWLEDGE_META: Extended metadata for knowledge entities
CREATE TABLE KNOWLEDGE_META (
    ENTITY_ID        NUMBER PRIMARY KEY,
    SOURCE_TYPE      VARCHAR2(32) DEFAULT 'MANUAL',
    SOURCE_ENTITY_IDS JSON,
    VALIDATION_STATUS VARCHAR2(32) DEFAULT 'PENDING',
    CONFIDENCE       NUMBER DEFAULT 0.8,
    VERSION          NUMBER DEFAULT 1,
    IS_CURRENT       VARCHAR2(1) DEFAULT 'Y',
    VALIDATED_AT     TIMESTAMP,
    DEPRECATED_AT    TIMESTAMP,
    CONSTRAINT FK_KM_ENTITY FOREIGN KEY (ENTITY_ID) REFERENCES ENTITIES(ENTITY_ID) ON DELETE CASCADE,
    CONSTRAINT CK_KM_VALIDATION CHECK (VALIDATION_STATUS IN ('PENDING','VALIDATED','REJECTED','DEPRECATED')),
    CONSTRAINT CK_KM_IS_CURRENT CHECK (IS_CURRENT IN ('Y','N')),
    CONSTRAINT CK_KM_CONFIDENCE CHECK (CONFIDENCE BETWEEN 0 AND 1)
);

COMMENT ON TABLE KNOWLEDGE_META IS 'Extended metadata for KNOWLEDGE-type entities';

-- ENTITY_EMBEDDINGS: Vector embeddings for semantic search
