PROMPT View: BRANCH_COMPARISON [NEW v3.3.0]
PROMPT ============================================================

CREATE OR REPLACE VIEW BRANCH_COMPARISON AS
SELECT
    b1.BRANCH_ID AS BRANCH_A,
    b2.BRANCH_ID AS BRANCH_B,
    b1.FORK_CONTEXT_ID AS COMMON_ANCESTOR,
    b1.WORKSPACE_ID,
    (SELECT COUNT(*) FROM WORKSPACE_CONTEXT wc WHERE wc.BRANCH_ID = b1.BRANCH_ID) AS CTX_COUNT_A,
    (SELECT COUNT(*) FROM WORKSPACE_CONTEXT wc WHERE wc.BRANCH_ID = b2.BRANCH_ID) AS CTX_COUNT_B,
    b1.AGENT_ID AS AGENT_A,
    b2.AGENT_ID AS AGENT_B,
    b1.BRANCH_TYPE AS TYPE_A,
    b2.BRANCH_TYPE AS TYPE_B,
    b1.BRANCH_STATUS AS STATUS_A,
    b2.BRANCH_STATUS AS STATUS_B
FROM CONTEXT_BRANCHES b1
JOIN CONTEXT_BRANCHES b2 ON b1.WORKSPACE_ID = b2.WORKSPACE_ID
    AND b1.FORK_CONTEXT_ID = b2.FORK_CONTEXT_ID
    AND b1.BRANCH_ID < b2.BRANCH_ID;

