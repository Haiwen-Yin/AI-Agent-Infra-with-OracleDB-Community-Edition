/

CREATE PROPERTY GRAPH ORACLE_MEMORY_GRAPH
    VERTEX TABLES (
        ENTITIES
            KEY ENTITY_ID
            PROPERTIES (ENTITY_ID, ENTITY_TYPE, NAME, DESCRIPTION, CATEGORY, PRIORITY, STATUS, VISIBILITY, CREATED_AT)
            LABEL ENTITIES
    )
    EDGE TABLES (
        ENTITY_EDGES
            KEY EDGE_ID
            SOURCE KEY SOURCE_ID REFERENCES ENTITIES(ENTITY_ID)
            DESTINATION KEY TARGET_ID REFERENCES ENTITIES(ENTITY_ID)
            PROPERTIES (EDGE_ID, EDGE_TYPE, STRENGTH, CONFIDENCE, CREATED_AT)
            LABEL ENTITY_EDGES
    );

