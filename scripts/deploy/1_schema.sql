-- JSON-Relational Duality Views
-- ============================================================

CREATE OR REPLACE JSON RELATIONAL DUALITY VIEW MEMORY_DV
    AS MEMORY_DV
    INSERT    ON ENTITIES
    UPDATE    ON ENTITIES
    DELETE    ON ENTITIES
    AS
    SELECT JSON {
        'entity_id'    : e.ENTITY_ID,
        'entity_type'  : e.ENTITY_TYPE,
        'name'         : e.NAME,
        'description'  : e.DESCRIPTION,
        'content'      : e.CONTENT,
        'category'     : e.CATEGORY,
        'priority'     : e.PRIORITY,
        'status'       : e.STATUS,
        'tags'         : e.TAGS,
        'metadata'     : e.METADATA,
        'owned_by_agent' : e.OWNED_BY_AGENT,
        'visibility'   : e.VISIBILITY,
        'accessible_to' : e.ACCESSIBLE_TO,
        'created_at'   : e.CREATED_AT,
        'updated_at'   : e.UPDATED_AT,
        'edges' : [
            SELECT JSON {
                'edge_id'   : eg.EDGE_ID,
                'edge_type' : eg.EDGE_TYPE,
                'target_id' : eg.TARGET_ID,
                'strength'  : eg.STRENGTH,
                'confidence': eg.CONFIDENCE
            }
            FROM ENTITY_EDGES eg
            WHERE eg.SOURCE_ID = e.ENTITY_ID
        ]
    }
    FROM ENTITIES e
    WHERE e.ENTITY_TYPE = 'MEMORY';

CREATE OR REPLACE JSON RELATIONAL DUALITY VIEW KNOWLEDGE_DV
    AS KNOWLEDGE_DV
    INSERT    ON ENTITIES
    UPDATE    ON ENTITIES
    DELETE    ON ENTITIES
    AS
    SELECT JSON {
        'entity_id'    : e.ENTITY_ID,
        'entity_type'  : e.ENTITY_TYPE,
        'name'         : e.NAME,
        'description'  : e.DESCRIPTION,
        'content'      : e.CONTENT,
        'category'     : e.CATEGORY,
        'status'       : e.STATUS,
        'tags'         : e.TAGS,
        'metadata'     : e.METADATA,
        'visibility'   : e.VISIBILITY,
        'created_at'   : e.CREATED_AT,
        'knowledge_meta' : (
            SELECT JSON {
                'source_type'       : km.SOURCE_TYPE,
                'validation_status' : km.VALIDATION_STATUS,
                'confidence'        : km.CONFIDENCE,
                'version'           : km.VERSION,
                'is_current'        : km.IS_CURRENT
            }
            FROM KNOWLEDGE_META km
            WHERE km.ENTITY_ID = e.ENTITY_ID
        ),
        'edges' : [
            SELECT JSON {
                'edge_id'   : eg.EDGE_ID,
                'edge_type' : eg.EDGE_TYPE,
                'target_id' : eg.TARGET_ID,
                'strength'  : eg.STRENGTH
            }
            FROM ENTITY_EDGES eg
            WHERE eg.SOURCE_ID = e.ENTITY_ID
        ]
    }
    FROM ENTITIES e
    WHERE e.ENTITY_TYPE = 'KNOWLEDGE';

